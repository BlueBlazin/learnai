# BUG: a special token at the end of the prompt is treated like any other: its bytes are empty, every token 'starts with' the empty string, so the special token is removed from the prompt and lost.
from whetstone.kit import ToyVocab


def heal(prompt_ids: list[int], vocab: ToyVocab) -> tuple[list[int], bytes]:
    pieces = [vocab.bytes(t) for t in range(vocab.size)]
    longest = max(len(piece) for piece in pieces)
    best = len(prompt_ids)  # where the kept part ends; nothing removed so far
    tail = b""
    # Grow the suffix one token at a time, from the end of the prompt backwards.
    for k in range(len(prompt_ids) - 1, -1, -1):
        piece = pieces[prompt_ids[k]]
        tail = piece + tail
        if len(tail) > longest:
            break  # no token is this long, and longer suffixes only grow
        single = len(prompt_ids) - k == 1
        if any(p.startswith(tail) and not (single and p == tail) for p in pieces):
            best = k
    removed = b"".join(pieces[t] for t in prompt_ids[best:])
    return list(prompt_ids[:best]), removed


def healing_allowed(required_prefix: bytes, generated_bytes: bytes, vocab: ToyVocab) -> list[int]:
    done = min(len(required_prefix), len(generated_bytes))
    if required_prefix[:done] != generated_bytes[:done]:
        raise ValueError("the generated bytes do not agree with the required prefix")
    remaining = required_prefix[done:]
    if not remaining:
        # The removed text is back: generation is unconstrained again, special
        # tokens included.
        return list(range(vocab.size))
    allowed = []
    for token in range(vocab.size):
        piece = vocab.bytes(token)
        # The token must agree with the remaining text for as long as both last: it
        # may stop short of it (a prefix) or run past it (an extension). A special
        # token has no bytes and would regenerate nothing, so it is excluded.
        if piece and (remaining.startswith(piece) or piece.startswith(remaining)):
            allowed.append(token)
    return allowed
