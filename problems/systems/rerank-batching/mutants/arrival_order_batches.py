# BUG: the pairs are batched in arrival order instead of sorted by length, so short pairs are padded to the long pairs they happen to arrive with.
def rerank(
    query: list[int],
    docs: list[list[int]],
    scorer,
    max_batch: int,
    top_n: int,
    max_tokens: int | None = None,
) -> tuple[list[float], list[int]]:
    room = scorer.max_length - len(query)
    pairs = [(query, doc[:room]) for doc in docs]
    lengths = [len(query) + len(doc) for _, doc in pairs]

    order = list(range(len(pairs)))

    batches: list[list[int]] = []
    width = 0
    for i in order:
        batch = batches[-1] if batches else None
        full = batch is None or len(batch) == max_batch
        if not full and max_tokens is not None:
            full = (len(batch) + 1) * max(width, lengths[i]) > max_tokens
        if full:
            batches.append([i])
            width = lengths[i]
        else:
            batch.append(i)
            width = max(width, lengths[i])

    scores = [0.0] * len(pairs)
    for batch in batches:
        for i, score in zip(batch, scorer([pairs[i] for i in batch]), strict=True):
            scores[i] = score

    ranking = sorted(range(len(scores)), key=lambda i: -scores[i])[: max(top_n, 0)]
    return scores, ranking
